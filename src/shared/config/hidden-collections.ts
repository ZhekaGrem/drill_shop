// Приховані розділи: колекції, які існують у БД і доступні прямим лінком,
// але не світяться у публічних списках (герої головної, картки каталогу).
// У «Іньчі колекції» під товаром вони, навпаки, ПОКАЗУЮТЬСЯ — рішення
// власника 2026-08-22: саме та секція стала для них входом.
// Бекендовий heroEnabled=false тут не годиться — він
// прибирає колекцію з GET /collections цілком, і сторінка товару втрачає
// назву колекції, свотчі та перемикач.
//
// Бонус прихованого розділу: на його сторінках словомарка логотипа в хедері
// змінюється (є. Дріл → є. Олько) — розділ живе під власним «брендом».
// «Вуйна» — серія, і кожен її автор живе під своєю словомаркою й окремою
// колекцією («Олько Вуйна», «Сєрік Вуйна»). Словомарка привʼязана саме до
// слага, тож без окремого запису обидва автори ділили б один бренд у хедері.
// Назви колекцій спершу збігалися — і щойно приховані розділи пустили в
// «Іньчі колекції», у списку зʼявилось дві однакові картки. Звідси й імена.
//
// Один розділ може мати КІЛЬКА колекцій: у «Поламава» футболки й худі живуть
// окремо (кожна зі своїм перемикачем на своїй 3D-моделі), але словомарка в
// обох одна — це один світ хедера.
export const HIDDEN_COLLECTION_SLUGS: readonly string[] = [
  'mystetstvo-viyny',
  'mystetstvo-viyny-serik',
  'polamav-futbolky',
  'polamav-hudi',
];

// Словомарка хедера для прихованого розділу (дефолтна — «Дріл»)
export const HIDDEN_COLLECTION_WORDMARK: Record<string, string> = {
  'mystetstvo-viyny': 'Олько',
  'mystetstvo-viyny-serik': 'Сєрік',
  'polamav-futbolky': 'Поламав',
  'polamav-hudi': 'Поламав',
};

export const isHiddenCollection = (slug: string | null | undefined): boolean =>
  !!slug && HIDDEN_COLLECTION_SLUGS.includes(slug);
