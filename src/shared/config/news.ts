// і саме за нею вирішується, чи показувати дзвіночок.

export interface NewsItem {
  /** Стабільний ідентифікатор: змінювати не можна — на ньому тримається
   *  мітка «прочитано» в браузері. Формат дати з темою зручний очима. */
  id: string;
  /** ISO YYYY-MM-DD; показуємо як «20 вересня» */
  date: string;
  title: string;
  /** Кілька речень. Працюють посилання [текст](/шлях), як в описах колекцій */
  text: string;
  /** Кольорова капсула біля заголовка: обидва поля разом або жодного */
  label?: string;
  labelColor?: string;
  /** Кнопка внизу новини */
  href?: string;
  hrefLabel?: string;
}

