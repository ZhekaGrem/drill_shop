/** Остання новина; null, коли список порожній */
export const latestNews = (news: NewsItem[] = NEWS): NewsItem | null => news[0] ?? null;

/** Чи є непрочитане. seen — id останньої прочитаної новини з браузера */
export const hasUnreadNews = (seen: string | null, news: NewsItem[] = NEWS): boolean => {
  const latest = latestNews(news);
  return latest !== null && seen !== latest.id;
};

/** «2026-09-20» → «20 вересня». Місяць у родовому відмінку, року немає:
 *  новини живуть тижнями, рік у стрічці тільки шумить. */
const MONTHS = [
  'січня',
  'лютого',
  'березня',
  'квітня',
  'травня',
  'червня',
  'липня',
  'серпня',
  'вересня',
  'жовтня',
  'листопада',
  'грудня',
];

export const formatNewsDate = (iso: string): string => {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!match) return iso;
  const [, , month, day] = match;
  const name = MONTHS[Number(month) - 1];
  return name ? `${Number(day)} ${name}` : iso;
};
