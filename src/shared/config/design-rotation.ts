// src/shared/config/design-rotation.ts
// Ротація кольористик: сайт сам міняє палітру кожні ROTATION_SLOT_DAYS діб.
//
// Джерело правди — КАЛЕНДАР, а не сховище. designForTime() це чиста функція
// часу, тож усі відвідувачі в один момент бачать одне й те саме, нічого не
// треба зберігати й нема чому розсинхронізуватись. Для нового відвідувача і
// для того, хто чистив кеш, відповідь однакова.
//
// Чому не сервер: сторінки статичні (SSG/ISR), а атрибут data-design ставить
// інлайн-скрипт до першого кадру. Якби палітру вирішував сервер, її довелось
// би або вшивати в HTML (і тоді кожен слот інвалідує весь CDN-кеш), або
// тягнути запитом (і тоді перший кадр блимає). Чиста функція часу не робить
// ні того, ні іншого — і не коштує жодного виклику функції на Vercel.
//
// Модуль НАВМИСНО без жодного звертання до document/localStorage: його
// імпортує серверний layout.tsx, щоб зібрати той самий інлайн-скрипт із тих
// самих констант (див. rotationSnippet нижче).
import type { DesignId } from './design';

/** Головний рубильник. false — сайт назавжди лишається на DESIGN_FALLBACK. */
export const ROTATION_ENABLED = true;

/**
 * Порядок ротації. Рішення власника (2026-08-21): Дія → Перегруз →
 * Сценічне → Індустріальна. К1–К3 у ротації НЕ беруть участі — вони міняють
 * ще й механіку героя та правило авто-теми, тобто це вже інший сайт, а не
 * інший колір. Вибрати їх руками з /v2/dev досі можна.
 */
export const ROTATION_ORDER: DesignId[] = ['diia', 'overdrive', 'spotlight', 'monolith'];

/** Скільки діб тримається кожна палітра. */
export const ROTATION_SLOT_DAYS = 2;

/**
 * Початок слоту Дії — від нього відлічуються всі інші.
 * 2026-08-20T21:00Z = 2026-08-21 00:00 за Києвом (EEST, UTC+3).
 *
 * Зсув -3 години вшитий у саму константу навмисно, замість окремого доданка:
 * так у формулі нема ЖОДНОЇ роботи з часовими поясами, а перемикання все одно
 * припадає на київську північ улітку (і на 01:00 узимку, бо літній час тут не
 * враховується — на дві доби різниці в годину не варта DST-математики в
 * інлайн-скрипті).
 *
 * Момент глобальний: він однаковий для всіх відвідувачів, звідки б вони не
 * зайшли. Це свідомо не «локальна північ» — інакше на питання «яка сьогодні
 * палітра» не було б однієї відповіді.
 *
 * Якір, а не старт: до цієї дати формула так само працює назад.
 */
export const ROTATION_ANCHOR_MS = Date.UTC(2026, 7, 20, 21, 0, 0);

const SLOT_MS = ROTATION_SLOT_DAYS * 86_400_000;

/** Номер слоту від якоря. Для часу до якоря — відʼємний, це нормально. */
export const rotationSlot = (now: number): number => Math.floor((now - ROTATION_ANCHOR_MS) / SLOT_MS);

/** Яка палітра має бути в цей момент. Чиста функція, без побічних ефектів. */
export const designForTime = (now: number): DesignId => {
  const n = ROTATION_ORDER.length;
  // Подвійний модуль, бо в JS (-1 % 4) === -1: без нього дати до якоря
  // впали б у від'ємний індекс і повернули undefined.
  return ROTATION_ORDER[((rotationSlot(now) % n) + n) % n];
};

/** Коли станеться наступна зміна (мс епохи). */
export const nextRotationAt = (now: number): number => ROTATION_ANCHOR_MS + (rotationSlot(now) + 1) * SLOT_MS;

/**
 * Той самий розрахунок, але рядком — для інлайн-скрипта в layout.tsx, який
 * мусить поставити атрибут ДО першого кадру і тому не може нічого імпортувати.
 *
 * Збирається з ТИХ САМИХ констант, що й designForTime вище. Це головне:
 * продублювати можна логіку (три рядки), але не дані — порядок, якір і довжину
 * слоту. Інакше ротація в скрипті та в React розʼїхалась би при першій же
 * правці порядку, і різницю було б видно лише як блимання при завантаженні.
 *
 * Лишає результат у змінній `ds`.
 */
export const rotationSnippet = (): string =>
  ROTATION_ENABLED
    ? `var RO=${JSON.stringify(ROTATION_ORDER)},RA=${ROTATION_ANCHOR_MS},RS=${SLOT_MS};` +
      `var rs=Math.floor((Date.now()-RA)/RS);ds=RO[((rs%RO.length)+RO.length)%RO.length];`
    : '';
