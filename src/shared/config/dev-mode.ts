// src/shared/config/dev-mode.ts
// Режим розробки — один перемикач для внутрішніх dev-інструментів, які
// покупцям не показуємо.
//
//   DEV_MODE = true  → дев-панель налаштувань /v2/dev відкрита (там і
//                      перемикач теми), так само /v2/lab, /v2/motion,
//                      /v2/switcher, /v2/swatches, /v2/loaders.
//   DEV_MODE = false → ці сторінки показують 404-екран. Дарк-мод при цьому
//                      ЖИВИЙ — просто керується лише годинником (18:00–6:00)
//                      без ручки.
//
// Десктопна заглушка-ґейт на решті сайту (раніше керувалась цим же
// прапорцем через LayoutWrapper) знята повністю — десктоп відкритий усюди
// незалежно від DEV_MODE.
// Локальні інструменти доступні в dev-сервері; production-збірка їх закриває.
export const DEV_MODE = process.env.NODE_ENV === 'development';
